#!/usr/bin/env node
// One-shot reconciliation of the Grok research desk's commit 5393021 ("Research Pons, Mancer, and Statics
// profiles", on origin/research/ecosystem-baseline) against main's source ledgers. The desk numbered its
// sources against an older ledger; main's ledgers for pons / mancer / statics-protocol grew past that
// numbering (Task 5 intake, harvest-metrics, grok feed rounds), so the desk's S-ids collide with main's.
//
// Rule (research-intake brief, step 2): main's ledger is the base. For each slug —
//   • an entry the desk MODIFIED (same id and same url as in its parent 5393021^ and in main) is refreshed
//     in place: publisher / kind / accessed_at / claim / excerpt take the desk's values, the id stays;
//   • an entry the desk ADDED (present in 5393021, absent from 5393021^) is renumbered after main's max id
//     and appended — unless main already has the same url, in which case that main id is reused and refreshed;
//   • every S-id in the desk's versions of projects/<slug>.yaml (findings / deployments / metrics) and
//     research/<slug>.md (evidence tags and the "## Sources" list) is remapped desk-id → main-id in one pass.
//
// Writes:  content/sources/<slug>.yaml            (main's file + refreshes + renumbered additions)
//          <out>/<slug>.project.yaml               (desk's project file, ids remapped — for hand-merge)
//          <out>/<slug>.research.md                (desk's research record, ids remapped — for hand-merge)
//          <out>/mapping.md                        (the id mapping table, also printed to stdout)
// Reads only git objects (never the working tree), so it is reproducible from any checkout that has fetched
// origin/research/ecosystem-baseline. Do not re-run against ledgers that already carry the renumbered entries —
// it regenerates content/sources/<slug>.yaml wholesale from --base, so it refuses to run without --overwrite
// (same convention as the other scripts in this directory: a confirmation, not a convenience).
//
//   node scripts/intake/2026-08-31/reconcile-desk-5393021.mjs --overwrite [--base origin/main] [--out build/intake/desk-5393021]

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse, parseDocument, isSeq, isScalar, visit } from "yaml";

const DESK = "5393021";
const PARENT = `${DESK}^`;
const SLUGS = ["pons", "mancer", "statics-protocol"];
const REFRESH_FIELDS = ["publisher", "kind", "accessed_at", "claim", "excerpt"];
const ENTRY_KEYS = ["id", "url", "publisher", "kind", "accessed_at", "claim", "excerpt", "hash", "archive_url", "researcher", "available"];

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i === -1 ? null : args[i + 1]; };
if (!args.includes("--overwrite")) {
  console.error("refusing to run: this regenerates content/sources/{pons,mancer,statics-protocol}.yaml from --base.\n" +
    "Pass --overwrite to confirm. Usage: node scripts/intake/2026-08-31/reconcile-desk-5393021.mjs --overwrite [--base origin/main] [--out build/intake/desk-5393021]");
  process.exit(2);
}
const base = flag("--base") ?? "origin/main";
const out = flag("--out") ?? "build/intake/desk-5393021";
mkdirSync(out, { recursive: true });

const show = (rev, path) => execFileSync("git", ["show", `${rev}:${path}`], { encoding: "utf8" });
const idNum = (id) => Number(String(id).slice(1));

const report = [`# Desk 5393021 → ${base} source-id mapping`, "", `Generated by scripts/intake/2026-08-31/reconcile-desk-5393021.mjs (base \`${base}\`).`, ""];

for (const slug of SLUGS) {
  const ledgerPath = `content/sources/${slug}.yaml`;
  const baseDoc = parseDocument(show(base, ledgerPath));
  const baseSeq = baseDoc.get("sources");
  if (!isSeq(baseSeq)) throw new Error(`${ledgerPath}@${base}: sources is not a list`);
  const baseById = new Map(baseSeq.items.map((n) => [n.get("id"), n]));
  const baseByUrl = new Map(baseSeq.items.map((n) => [n.get("url"), n]));
  const deskEntries = parse(show(DESK, ledgerPath)).sources;
  const parentEntries = parse(show(PARENT, ledgerPath)).sources;
  const parentById = new Map(parentEntries.map((e) => [e.id, e]));
  let max = Math.max(...[...baseById.keys()].map(idNum));

  const idMap = new Map();
  const rows = [];
  const refresh = (node, e) => {
    const changed = REFRESH_FIELDS.filter((f) => node.get(f) !== e[f]);
    for (const f of changed) node.set(f, e[f]);
    return changed;
  };

  for (const e of deskEntries) {
    const parent = parentById.get(e.id);
    const baseNode = baseById.get(e.id);
    if (parent && baseNode && baseNode.get("url") === e.url) {
      // Same id, same url on all three sides: identity mapping. Refresh only if the desk changed the entry.
      const deskChanged = REFRESH_FIELDS.some((f) => parent[f] !== e[f]);
      const changed = deskChanged ? refresh(baseNode, e) : [];
      idMap.set(e.id, e.id);
      rows.push({ desk: e.id, main: e.id, action: deskChanged ? `refreshed in place (${changed.join(", ") || "no field differed from main"})` : "unchanged", url: e.url });
      continue;
    }
    const byUrl = baseByUrl.get(e.url);
    if (byUrl) {
      const changed = refresh(byUrl, e);
      idMap.set(e.id, byUrl.get("id"));
      rows.push({ desk: e.id, main: byUrl.get("id"), action: `matched main by url; refreshed (${changed.join(", ") || "identical"})`, url: e.url });
      continue;
    }
    const newId = `S${++max}`;
    const node = baseDoc.createNode(Object.fromEntries(ENTRY_KEYS.map((k) => [k, k === "id" ? newId : e[k] ?? null])));
    baseSeq.add(node);
    idMap.set(e.id, newId);
    rows.push({ desk: e.id, main: newId, action: parent ? "id collided with a different main entry; appended under a new id" : "added by the desk; appended after main's max id", url: e.url });
  }

  const map = (id) => {
    if (!idMap.has(id)) throw new Error(`${slug}: desk cites ${id}, which is not in its ledger at ${DESK}`);
    return idMap.get(id);
  };

  // projects/<slug>.yaml — remap every sources:/evidence: list, leave everything else for the hand-merge.
  const projectDoc = parseDocument(show(DESK, `content/projects/${slug}.yaml`));
  visit(projectDoc, {
    Pair(_, pair) {
      const key = isScalar(pair.key) ? pair.key.value : null;
      if ((key === "sources" || key === "evidence") && isSeq(pair.value))
        for (const item of pair.value.items) if (isScalar(item) && /^S\d+$/.test(String(item.value))) item.value = map(String(item.value));
    },
  });

  // research/<slug>.md — remap ids inside evidence tags and the "- S<n> — …" lines of ## Sources, in one pass.
  const research = show(DESK, `content/research/${slug}.md`)
    .replace(/\[(verified|claim|inference|disputed)((?:\s+S\d+)+)\]/g, (_, cls, ids) => `[${cls}${ids.replace(/S\d+/g, map)}]`)
    .replace(/^(- )(S\d+)( — )/gm, (_, a, id, b) => a + map(id) + b);

  writeFileSync(ledgerPath, baseDoc.toString({ lineWidth: 0 }));
  writeFileSync(join(out, `${slug}.project.yaml`), projectDoc.toString({ lineWidth: 0 }));
  writeFileSync(join(out, `${slug}.research.md`), research);

  report.push(`## ${slug}`, "", `Main max id before: S${Math.max(...[...baseById.keys()].map(idNum))} · after: S${max}`, "", "| desk id | main id | action | url |", "|---|---|---|---|");
  for (const r of rows) report.push(`| ${r.desk} | ${r.main} | ${r.action} | ${r.url} |`);
  report.push("");
}

const text = report.join("\n");
writeFileSync(join(out, "mapping.md"), text + "\n");
console.log(text);
console.log(`wrote content/sources/{${SLUGS.join(",")}}.yaml and ${out}/{<slug>.project.yaml,<slug>.research.md,mapping.md}`);
